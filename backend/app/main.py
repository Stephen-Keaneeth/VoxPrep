class GlobalExceptionMiddleware:
    """
    Pure ASGI middleware that catches unhandled exceptions escaping the application,
    logs the stack trace securely, and sends a standardized HTTP 500 JSON response.
    Operates without anyio/event loop dependencies, ensuring flawless operation in
    both local ASGI test clients and production uvicorn ASGI servers.
    """

    def __init__(self, asgi_app):
        self.asgi_app = asgi_app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            await self.asgi_app(scope, receive, send)
            return

        response_started = False

        async def custom_send(message):
            nonlocal response_started
            if message["type"] == "http.response.start":
                response_started = True
            await send(message)

        try:
            await self.asgi_app(scope, receive, custom_send)
        except Exception as exc:
            logger.error(
                f"Unhandled exception during {scope.get('method', 'UNKNOWN')} {scope.get('path', 'UNKNOWN')}: {exc}",
                exc_info=True,
            )
            if not response_started:
                # Defense-in-depth: Inspect scope headers for requesting Origin
                origin = None
                for header_key, header_val in scope.get("headers", []):
                    key_str = header_key.decode("latin1").lower() if isinstance(header_key, bytes) else str(header_key).lower()
                    if key_str == "origin":
                        origin = header_val.decode("latin1") if isinstance(header_val, bytes) else str(header_val)
                        break

                cors_headers = None
                if origin:
                    cors_headers = {
                        "Access-Control-Allow-Origin": origin,
                        "Access-Control-Allow-Credentials": "true",
                        "Vary": "Origin",
                    }

                resp = JSONResponse(
                    status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                    content={
                        "detail": "Internal server error occurred.",
                        "error_type": "internal_server_error",
                        "status_code": 500,
                    },
                    headers=cors_headers,
                )
                await resp(scope, receive, send)


# Register GlobalExceptionMiddleware BEFORE CORSMiddleware.
# Because Starlette's app.add_middleware prepends to user_middleware (insert(0, ...)),
# registering GlobalExceptionMiddleware first and CORSMiddleware second ensures
# CORSMiddleware is the outermost layer, allowing it to process responses (including 500s)
# generated by GlobalExceptionMiddleware.
app.add_middleware(GlobalExceptionMiddleware)


# Configure CORS Middleware (registered AFTER GlobalExceptionMiddleware so CORSMiddleware is outermost)
allowed_origins = get_allowed_origins()

# W3C CORS Compliance & Browser Compatibility:
# Per W3C Fetch Spec Section 3.2.2, browsers reject responses containing
# 'Access-Control-Allow-Origin: *' when 'Access-Control-Allow-Credentials' is true.
# When wildcard development mode ("*" in allowed_origins) is active, we use
# allow_origin_regex=r".*" so Starlette dynamically reflects the requesting origin
# with 'Vary: Origin' and 'Access-Control-Allow-Credentials: true', fully conforming
# to the W3C spec and avoiding browser client failures.
# In production with explicit origins, exact origins are enforced without regex.
if "*" in allowed_origins:
    app.add_middleware(
        CORSMiddleware,
        allow_origins=[],
        allow_origin_regex=r".*",
        allow_credentials=True,
        allow_methods=["*"],
        allow_headers=["*"],
    )
else:
    app.add_middleware(
        CORSMiddleware,
        allow_origins=allowed_origins,
        allow_credentials=True,
        allow_methods=["*"],
        allow_headers=["*"],
    )


@app.exception_handler(StarletteHTTPException)
async def http_exception_handler(request: Request, exc: StarletteHTTPException) -> JSONResponse:
    """
    Global handler for HTTP exceptions (4xx / 5xx).
    Returns uniform JSON structure with detail, error_type, and status_code,
    preserving exact detail strings expected by client callers and test suites.
    """
    return JSONResponse(
        status_code=exc.status_code,
        content={
            "detail": exc.detail,
            "error_type": "http_error",
            "status_code": exc.status_code,
        },
        headers=getattr(exc, "headers", None),
    )


@app.exception_handler(RequestValidationError)
async def validation_exception_handler(request: Request, exc: RequestValidationError) -> JSONResponse:
    """
    Global handler for Pydantic / FastAPI request validation errors (HTTP 422).
    Returns uniform JSON structure with detail list, error_type, and status_code.
    """
    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content={
            "detail": jsonable_encoder(exc.errors()),
            "error_type": "validation_error",
            "status_code": 422,
        },
    )


@app.exception_handler(Exception)
async def generic_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """
    Global handler for unexpected internal exceptions (HTTP 500).
    Logs traceback securely and returns clean JSON without leaking stack details.
    """
    logger.error(
        f"Unhandled server exception during {request.method} {request.url.path}: {exc}",
        exc_info=True,
    )
    origin = request.headers.get("origin")
    headers = None
    if origin:
        headers = {
            "Access-Control-Allow-Origin": origin,
            "Access-Control-Allow-Credentials": "true",
            "Vary": "Origin",
        }
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content={
            "detail": "Internal server error occurred.",
            "error_type": "internal_server_error",
            "status_code": 500,
        },
        headers=headers,
    )


